    private void agregarNeuronaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarNeuronaActionPerformed
        // TODO add your handling code here:
        if (!controladorDisponible()) { //Evitar que el código se rompa si hay un error al cargar el controlador
            return;
        }

        String id = javax.swing.JOptionPane.showInputDialog(
                this,
                "Ingrese el ID de la nueva neurona:",
                "Agregar neurona",
                javax.swing.JOptionPane.QUESTION_MESSAGE
        );
        
        //Consideración de posibles casos de error
        if (id == null) { //No se introduce un ID
            return;
        }

        id = id.trim(); //Se eliminan los espacios al principio y al final del input 

        if (id.isEmpty()) { //Se muestra un mensaje de error alertando al usuario
            mostrarAdvertencia("El ID de la neurona no puede estar vacío.");
            return;
        }

        try {
            //Se guarda la respuesta del usuario y se procesa la solicitud
            String mensaje = controlador.agregarNeurona(id);
            actualizarDespuesDeCambio(mensaje);

            //Se informa al usuario del éxito de la operación
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensaje,
                    "Neurona agregada",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
        } catch (Exception e) { //Se informa al usuario sobre errores ocurridos
            mostrarError("Error al agregar neurona: " + e.getMessage());
        } 
    }//GEN-LAST:event_agregarNeuronaActionPerformed

    private void agregarSinapsisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarSinapsisActionPerformed
        // TODO add your handling code here:
        if (!controladorDisponible()) { //Evitar que el código se rompa si hay un error al cargar el controlador
            return;
        }
        
        //Creación de ventana temporal que solicita los datos necesarios para agregar una sinapsis 
        javax.swing.JTextField txtOrigen = new javax.swing.JTextField();
        javax.swing.JTextField txtDestino = new javax.swing.JTextField();
        javax.swing.JTextField txtDistancia = new javax.swing.JTextField();
        javax.swing.JTextField txtNeurotransmisor = new javax.swing.JTextField();
        javax.swing.JTextField txtK = new javax.swing.JTextField("1");

        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 1, 5, 5));

        panel.add(new javax.swing.JLabel("Neurona origen:"));
        panel.add(txtOrigen);

        panel.add(new javax.swing.JLabel("Neurona destino:"));
        panel.add(txtDestino);

        panel.add(new javax.swing.JLabel("Distancia sináptica:"));
        panel.add(txtDistancia);

        panel.add(new javax.swing.JLabel("ID neurotransmisor:"));
        panel.add(txtNeurotransmisor);

        panel.add(new javax.swing.JLabel("Coeficiente k (0 < k <= 1):"));
        panel.add(txtK);

        // Continuar o cancelar la creación de la sinapsis
        int opcion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                panel,
                "Agregar sinapsis dirigida",
                javax.swing.JOptionPane.OK_CANCEL_OPTION,
                javax.swing.JOptionPane.PLAIN_MESSAGE
        );

        if (opcion != javax.swing.JOptionPane.OK_OPTION) {
            return;
        }
        
        //Optimización y prevención de errores en el procesamiento al usar .trim()
        String origen = txtOrigen.getText().trim();
        String destino = txtDestino.getText().trim();
        String neurotransmisor = txtNeurotransmisor.getText().trim();

        if (origen.isEmpty() || destino.isEmpty() || neurotransmisor.isEmpty()) {
            mostrarAdvertencia("Origen, destino y neurotransmisor son obligatorios.");
            return; //Se advierte al usuario si faltan datos
        }

        try {
            //Extracción del contenido introducido para ser enviado al controlador
            double distancia = convertirDouble(txtDistancia.getText(), "distancia");
            double k = convertirDouble(txtK.getText(), "k");

            //Se aplican los cambios
            String mensaje = controlador.agregarSinapsis(origen, destino, distancia, neurotransmisor, k);
            actualizarDespuesDeCambio(mensaje);

            //Se informa al usuario del éxito de la operación
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensaje,
                    "Sinapsis agregada",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
        
        //Posibles casos de error y su respectivo manejo
        } catch (NumberFormatException e) {
            mostrarError("Distancia y k deben ser valores numéricos válidos.");
        } catch (Exception e) {
            mostrarError("Error al agregar sinapsis: " + e.getMessage());
        }   
    }//GEN-LAST:event_agregarSinapsisActionPerformed

    private void eliminarSinapsisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eliminarSinapsisActionPerformed
        // TODO add your handling code here:
        if (!controladorDisponible()) { //Evitar que el código se rompa si hay un error al cargar el controlador
            return;
        }

        // Creación de una ventana emergente que permite introducir datos necesarios para la operación
        javax.swing.JTextField txtOrigen = new javax.swing.JTextField();
        javax.swing.JTextField txtDestino = new javax.swing.JTextField();

        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 1, 5, 5));

        panel.add(new javax.swing.JLabel("Neurona origen:"));
        panel.add(txtOrigen);

        panel.add(new javax.swing.JLabel("Neurona destino:"));
        panel.add(txtDestino);

        //Continuar o cancelar la acción
        int opcion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                panel,
                "Eliminar sinapsis dirigida",
                javax.swing.JOptionPane.OK_CANCEL_OPTION,
                javax.swing.JOptionPane.PLAIN_MESSAGE
        );

        if (opcion != javax.swing.JOptionPane.OK_OPTION) {
            return;
        }

        //Procesamiento de datos introducidos
        String origen = txtOrigen.getText().trim();
        String destino = txtDestino.getText().trim();

        if (origen.isEmpty() || destino.isEmpty()) {
            mostrarAdvertencia("Origen y destino son obligatorios.");
            return; //Se alerta al usuario por falta de datos
        }
        
        // Confirmación final para llevar a cabo la operación
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Seguro que desea eliminar la sinapsis dirigida " + origen + " -> " + destino + "?",
                "Confirmar eliminación",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            // Extraer los datos introducidos y enviarlos al controlador para ejecutar la acción
            String mensaje = controlador.eliminarSinapsis(origen, destino);
            actualizarDespuesDeCambio(mensaje);

            //Informe de éxito
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensaje,
                    "Sinapsis eliminada",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
        } catch (Exception e) { //Informe de error
            mostrarError("Error al eliminar sinapsis: " + e.getMessage());
        }
    }//GEN-LAST:event_eliminarSinapsisActionPerformed

    private void guardarRedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarRedActionPerformed
        // TODO add your handling code here:
        if (!controladorDisponible()) { //Evitar que el código se rompa si el controlador no logra cargarse
            return;
        }
        
        /**
        * Creación de una ventana temporal con filtro de solo archivos CSV 
        * para guardar la red actual en un nuevo archivo dentro del ordenador.
        */
        
        javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
        selector.setDialogTitle("Guardar red sináptica");
        selector.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Archivos CSV (*.csv)", "csv"));
        selector.setSelectedFile(new java.io.File("red_sinaptica_guardada.csv"));

        int opcion = selector.showSaveDialog(this);

        if (opcion != javax.swing.JFileChooser.APPROVE_OPTION) {
            return;
        }

        java.io.File archivo = selector.getSelectedFile();

        //Evaluar si el archivo ya existe y decidir si reemplazarlo o no
        if (archivo.exists()) {
            int reemplazar = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "El archivo ya existe. ¿Desea reemplazarlo?",
                    "Confirmar guardado",
                    javax.swing.JOptionPane.YES_NO_OPTION,
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            if (reemplazar != javax.swing.JOptionPane.YES_OPTION) {
                return; //No se reemplazó el archivo
            }
        }

        try {
            //Se envían los datos al controlador
            String mensaje = controlador.guardarRed(archivo);

            if (panelResultados != null) { //Se registra la operación en el panel de resultados
                panelResultados.registrarOperacionSistema(mensaje);
            }

            //Informe de éxito
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensaje,
                    "Red guardada",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
        } catch (Exception e) { //Informe de error
            mostrarError("Error al guardar la red: " + e.getMessage());
        }
    }//GEN-LAST:event_guardarRedActionPerformed

    private void btnSalirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalirActionPerformed
        // TODO add your handling code here:
        
        //Se desea salir pero hay cambios sin guardar en el sistema
        if (controlador != null && controlador.hayCambiosSinGuardar()) {
            int opcion = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    //El sistema pide confirmación al usuario
                    "Hay cambios sin guardar. ¿Desea salir de todas formas?",
                    "Confirmar salida",
                    javax.swing.JOptionPane.YES_NO_OPTION,
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            if (opcion != javax.swing.JOptionPane.YES_OPTION) {
                return; 
            }
        } else {
            //No se han realizado cambios y el usuario desea salir del sistema
            int opcion = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    //Se pide confirmación al usuario
                    "¿Desea salir del sistema?",
                    "Confirmar salida",
                    javax.swing.JOptionPane.YES_NO_OPTION,
                    javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (opcion != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }
        }

        java.awt.Window ventana = javax.swing.SwingUtilities.getWindowAncestor(this);

        if (ventana != null) {
            ventana.dispose(); // Cierra la ventana de interfaz
        }

        System.exit(0); // Comando de terminación del programa.
    }//GEN-LAST:event_btnSalirActionPerformed


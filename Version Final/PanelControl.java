    private void btnCargarRedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarRedActionPerformed
        // TODO add your handling code here:
        if (controlador == null) { //Evitar que el programa se rompa si no se inicializa el controlador
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error interno: el controlador no fue inicializado.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        // En el caso de querer sustituir la red sináptica actual, se pide confirmación al usuario
        if (controlador.requiereConfirmacionParaNuevaRed()) {
            int opcion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Hay cambios sin guardar en la red actual. ¿Deseas cargar una nueva red y reemplazar los datos en memoria?",
                "Confirmar nueva carga",
                javax.swing.JOptionPane.YES_NO_OPTION
            );

            if (opcion != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }
        }

        // Despliegue de un JFileChooser para elegir una red sináptica
        javax.swing.JFileChooser selectorArchivos = new javax.swing.JFileChooser();
        selectorArchivos.setDialogTitle("Seleccione el archivo CSV de la Red Sináptica");
        
        // Implementación de un filtro que solo permita elegir archivos CSV del ordenador
        javax.swing.filechooser.FileNameExtensionFilter filtroCSV =
            new javax.swing.filechooser.FileNameExtensionFilter("Archivos CSV (*.csv)", "csv");

        selectorArchivos.setFileFilter(filtroCSV);

        int respuesta = selectorArchivos.showOpenDialog(this);

        if (respuesta == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File archivoSeleccionado = selectorArchivos.getSelectedFile();

        try {
            // Se envían los datos de la operación al controlador
            String mensaje = controlador.cargarRed(archivoSeleccionado);

            // Cambio en el texto debajo del botón cargar red, confirmando que el archivo se haya cargado
            lblEstadoRed.setText("Estado: Cargada (" + archivoSeleccionado.getName() + ")");
            lblEstadoRed.setForeground(new java.awt.Color(0, 153, 0));

            // Envío de información al panel de resultados
            if (panelResultados != null) {
                panelResultados.registrarOperacionSistema(
                        "Red sináptica cargada exitosamente desde: " + archivoSeleccionado.getName()
                );

                panelResultados.mostrarReporteCarga(
                        "Reporte de carga de red",
                        controlador.getUltimoReporteCargaRed()
                );
            }   

            // Actualización del grafo visual
            if (visualizadorGrafo != null) {
                visualizadorGrafo.actualizarGrafo(controlador.getGrafo());
            }

            // Informe de éxito
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensaje,
                    "Carga exitosa",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

        } catch (Exception e) { // Informe de error
            lblEstadoRed.setText("Estado: Error al cargar");
            lblEstadoRed.setForeground(java.awt.Color.RED);
            // Se actualiza el texto debajo del botón a un mensaje de error de color rojo
            
            String mensajeError = "Error al cargar la red: " + e.getMessage();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensajeError,
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            // Se registra en el panel de resultados
            if (panelResultados != null) {
                panelResultados.registrarOperacionSistema(mensajeError);

                panelResultados.mostrarReporteCarga(
                        "Reporte de error al cargar red",
                        controlador.getUltimoReporteCargaRed()
                );
            }
          }
        }
    }//GEN-LAST:event_btnCargarRedActionPerformed

    private void btnCargarNeuroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarNeuroActionPerformed
        // TODO add your handling code here:
        if (controlador == null) { // Evitar que se rompa el programa si no se inicializa el controlador
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error interno: el controlador no fue inicializado.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        // Despliegue de un JFileChooser para cargar el archivo con los neurotransmisores
        javax.swing.JFileChooser selectorArchivos = new javax.swing.JFileChooser();
        selectorArchivos.setDialogTitle("Seleccione el archivo CSV de Neurotransmisores");

        // Filtro que solo permite elegir archivos CSV del ordenador
        javax.swing.filechooser.FileNameExtensionFilter filtroCSV =
            new javax.swing.filechooser.FileNameExtensionFilter("Archivos CSV (*.csv)", "csv");

        selectorArchivos.setFileFilter(filtroCSV);

        int respuesta = selectorArchivos.showOpenDialog(this);

        // Confirmación de cargado
        if (respuesta == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File archivoSeleccionado = selectorArchivos.getSelectedFile();

        try {
            // Envío de datos de la operación al controlador
            String mensaje = controlador.cargarDiccionario(archivoSeleccionado);

            lblEstadoNeuro.setText("Estado: Cargado (" + archivoSeleccionado.getName() + ")");
            lblEstadoNeuro.setForeground(new java.awt.Color(0, 153, 0));

            // Registro de la operación en el panel de resultados
            if (panelResultados != null) {
                panelResultados.registrarOperacionSistema(
                        "Diccionario de neurotransmisores cargado desde: " + archivoSeleccionado.getName()
                );

                // Informe de error
                panelResultados.mostrarReporteCarga(
                        "Reporte de carga de neurotransmisores",
                        controlador.getUltimoReporteCargaNeurotransmisores()
                );
            }

            // Informe de éxito
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensaje,
                    "Carga exitosa",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

        } catch (Exception e) { // Error al cargar el archivo CSV
            lblEstadoNeuro.setText("Estado: Error al cargar");
            lblEstadoNeuro.setForeground(java.awt.Color.RED); 
            // Se actualiza el texto debajo del botón a un mensaje de error de color rojo

            // Se informa al usuario
            String mensajeError = "Error al cargar neurotransmisores: " + e.getMessage();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    mensajeError,
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            // Se registra el informe de error en el panel de resultados
            if (panelResultados != null) {
                panelResultados.registrarOperacionSistema(mensajeError);

                panelResultados.mostrarReporteCarga(
                        "Reporte de error al cargar neurotransmisores",
                        controlador.getUltimoReporteCargaNeurotransmisores()
                );
                }
              }
            }
    }//GEN-LAST:event_btnCargarNeuroActionPerformed


    private boolean controladorDisponible() {
        if (controlador == null) {
            mostrarError("Error interno: el controlador no fue inicializado.");
            return false;
        }
        return true;
        }

    private void actualizarDespuesDeCambio(String mensaje) {
        if (panelResultados != null) {
            panelResultados.registrarOperacionSistema(mensaje);
        }

        if (visualizadorGrafo != null) {
            visualizadorGrafo.actualizarGrafo(controlador.getGrafo());
            }
        }

    private void mostrarAdvertencia(String mensaje) { 
        javax.swing.JOptionPane.showMessageDialog(
                this,
                mensaje,
                "Validación",
                javax.swing.JOptionPane.WARNING_MESSAGE
    );
}

    private void mostrarError(String mensaje) {
        if (panelResultados != null) {
            panelResultados.mostrarErrorValidacion(mensaje);
        }

        javax.swing.JOptionPane.showMessageDialog(
                this,
                mensaje,
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    //Conversión de ciertos datos introducidos al tipo double para ser procesados por el controlador
    private double convertirDouble(String texto, String campo) {
        if (texto == null || texto.trim().isEmpty()) {
            throw new NumberFormatException("El campo " + campo + " está vacío.");
        }

        return Double.parseDouble(texto.trim().replace(',', '.'));
    }


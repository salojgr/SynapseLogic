    private void btnTraumatismoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTraumatismoActionPerformed
        // TODO add your handling code here:
        
        // Se extrae el texto introducido en el TextField
        String idEliminar = txtTraumatismo.getText().trim();
    
        // Se informa al usuario si no se han introducido valores
        if (idEliminar.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el ID de la neurona a dañar.", "Campo Vacío", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Se solicita confirmación al usuario
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, "¿Estás seguro de que deseas eliminar la neurona " + idEliminar + "? Esta acción no se puede deshacer.", "Confirmar Traumatismo", javax.swing.JOptionPane.YES_NO_OPTION);
        
        // Se confirma la acción
        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            try {
                
                // Se llama al método para eliminar la neurona
                controlador.simularTraumatismo(idEliminar);
                
                // Registro de la operación en consola
                if (panelResultados != null) {
                    panelResultados.registrarOperacionSistema("TRAUMATISMO CRÍTICO: Se ha eliminado permanentemente la neurona con ID: " + idEliminar);
                }
                
                // Actualización del grafo
                if (visualizadorGrafo != null) {
                    visualizadorGrafo.actualizarGrafo(controlador.getGrafo());
                }

                // Informe de éxito
                javax.swing.JOptionPane.showMessageDialog(this, "Neurona " + idEliminar + " eliminada por traumatismo.", "Traumatismo Exitoso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                txtTraumatismo.setText("");
                
            } catch (Exception e) { //Casos de error y alerta al usuario
                if (panelResultados != null) {
                    panelResultados.mostrarErrorValidacion("Fallo al intentar destruir neurona " + idEliminar + ": " + e.getMessage());
                }
                javax.swing.JOptionPane.showMessageDialog(this, "Error en el traumatismo: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnTraumatismoActionPerformed



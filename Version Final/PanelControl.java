    private void btnDijkstraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDijkstraActionPerformed
        // TODO add your handling code here:
        
        // Se extrae el texto introducido en los TextField, aplicando .trim() al mismo tiempo
        String origen = txtDijkstraOrigen.getText().trim();
        String destino = txtDijkstraDestino.getText().trim();

        // Alertar al usuario sobre la introducción de datos inválidos (vacío)
        if (origen.isEmpty() || destino.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Por favor, ingresa origen y destino.",
                "Campos Vacíos",
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // Procesamiento de datos enviados al método del controlador
            Ruta rutaResultante = controlador.calcularRuta(origen, destino);

            // Registro de la operación en la consola
            if (panelResultados != null) {
                panelResultados.mostrarRuta(rutaResultante);
            }

            // Comprobación de que la ruta existe
            if (rutaResultante.existeRuta()) {

                // Resaltar las líneas en el visualizador del grafo
                if (visualizadorGrafo != null) {
                    visualizadorGrafo.resaltarRuta(rutaResultante.getSecuenciaNeuronas());
                }

                // Formatear el texto usando el método toString() de la clase Ruta
                String mensaje = rutaResultante.toString();
                javax.swing.JOptionPane.showMessageDialog(this, mensaje, "Ruta Óptima", javax.swing.JOptionPane.INFORMATION_MESSAGE);

            } else {
                // Llamada al método getMensaje()de la clase Ruta
                javax.swing.JOptionPane.showMessageDialog(this, rutaResultante.getMensaje(), "Sin Ruta", javax.swing.JOptionPane.WARNING_MESSAGE);
            }

        } catch (Exception e) { // Se atrapan errores y se informa al usuario
            javax.swing.JOptionPane.showMessageDialog(this, "Error al calcular Dijkstra: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDijkstraActionPerformed

